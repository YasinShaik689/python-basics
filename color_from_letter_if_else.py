alphabet = input("enter an alphabet: ")
if alphabet == "v":
    print("Violet")
elif alphabet == "i":
    print("Indigo")
elif alphabet == "b":
    print("Blue")
elif alphabet == "g":
    print("Green")
elif alphabet == "y":
    print("Yellow")
elif alphabet == "o":
    print("Orange")
elif alphabet == "r":
    print("Red")
else:
    print("Invalid colour")
