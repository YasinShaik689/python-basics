alphabet = input("enter the alphabet: ")
match alphabet:
    case "v":
        print("Violet")
    case "i":
        print("Indigo")
    case "b":
        print("Blue")
    case "g":
        print("Green")
    case "y":
        print("Yellow")
    case "o":
        print("Orange")
    case "r":
        print("Red")
    case _:
        print("Invalid colour")
